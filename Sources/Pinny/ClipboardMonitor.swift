import AppKit

/// Vigila el portapapeles general consultando `changeCount`.
@MainActor
final class ClipboardMonitor {
    /// `changeCount` de escrituras hechas por la propia Pinny al pegar (y al restaurar
    /// lo que tenías copiado). Se ignoran para no ensuciar el historial.
    static var ownChangeCounts: Set<Int> = []

    private var timer: Timer?
    private var lastChange = NSPasteboard.general.changeCount

    /// Tipos que los gestores de contraseñas y otras apps marcan como no guardables.
    private let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword"
    ]

    func start() {
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.check() }
        }
        // Modos comunes: así sigue vigilando aunque haya un panel modal abierto.
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func check() {
        let pasteboard = NSPasteboard.general
        let current = pasteboard.changeCount
        guard current != lastChange else { return }
        lastChange = current

        let isOwnWrite = Self.ownChangeCounts.contains(current)
        Self.ownChangeCounts = Self.ownChangeCounts.filter { $0 > current }
        guard !isOwnWrite else { return }

        guard !Settings.shared.capturePaused else { return }

        let types = Set((pasteboard.types ?? []).map { $0.rawValue })
        guard types.isDisjoint(with: ignoredTypes) else { return }

        // Aproximación: la app en primer plano es la que acaba de copiar.
        if let bundleID = NSWorkspace.shared.frontmostApplication?.bundleIdentifier,
           Settings.shared.ignoredBundleIDs.contains(bundleID) {
            return
        }

        if let text = pasteboard.string(forType: .string) {
            ClipStore.shared.add(text)
        }
    }
}
